'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const crypto=require('node:crypto');
const html=fs.readFileSync('quote-scope-diff.html','utf8');
let passed=0;
function test(name,fn){fn();passed++;console.log('PASS '+name);}
const scripts=[...html.matchAll(/<script id="[^"]+">([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const context=vm.createContext({Intl});
vm.runInContext(scripts[0],context);
const S=context.ScopeDiff;
test('script syntax',()=>scripts.forEach(code=>new vm.Script(code)));
test('negative evidence and line numbers preserved',()=>{const t=S.scan('Permits excluded.\nEngineering not included.');assert.equal(t.find(x=>x.id==='permits').hits[0].text,'Permits excluded.');assert.equal(t.find(x=>x.id==='engineering').hits[0].line,2);});
test('no automatic inclusion classification',()=>assert.equal(S.scan('Permits included.')[3].status,undefined));
test('missing keywords remain unknown',()=>assert.equal(S.scan('hello there')[3].hits.length,0));
test('up to three excerpts',()=>assert.equal(S.scan('Permit one\nPermit two\nPermit three\nPermit four')[3].hits.length,3));
test('large line evidence clipped around actual match',()=>{const h=S.scan('X'.repeat(900)+' permits excluded '+'y'.repeat(900))[3].hits[0];assert.equal(h.clipped,true);assert.ok(h.text.includes('permits excluded'));assert.ok(h.text.length<=710);});
test('input bounds and blanks',()=>{assert.throws(()=>S.scan('x'.repeat(100001)));assert.throws(()=>S.scan('a\n'.repeat(3001)));assert.throws(()=>S.scan(' '));});
test('missing total different from zero',()=>{assert.equal(S.cents(''),null);assert.equal(S.cents('0'),0);assert.equal(S.cents('15,000.25'),1500025);});
test('invalid money rejected',()=>{for(const v of ['-1','1e5','12.345','Infinity','12,50','10000001'])assert.throws(()=>S.cents(v));});
test('unknown does not create confirmed difference',()=>assert.equal(S.difference(['review','included','unclear']),false));
test('manual included vs excluded is a difference',()=>assert.equal(S.difference(['included','excluded','review']),true));
test('all included agree without proof of equivalent scope',()=>assert.equal(S.difference(['included','included']),false));
test('CSP hashes match executable code and styles',()=>{for(const match of html.matchAll(/<(?:script id="[^"]+"|style)>([\s\S]*?)<\/(?:script|style)>/g)){const hash=crypto.createHash('sha256').update(match[1]).digest('base64');assert.ok(html.includes("'sha256-"+hash+"'"));}});
test('no dynamic HTML sinks',()=>assert.ok(!/\.innerHTML\s*=|insertAdjacentHTML/.test(html)));
test('no document persistence APIs',()=>assert.ok(!/localStorage|sessionStorage|indexedDB|setItem\(/.test(html)));
test('no document network API calls',()=>assert.ok(!/\bfetch\(|XMLHttpRequest|sendBeacon\(/.test(html)));
test('sitemap discovery',()=>assert.ok(fs.readFileSync('sitemap-growth.xml','utf8').includes('https://repaircostmatch.com/quote-scope-diff.html')));
console.log(passed+' isolated comparison tests passed.');
